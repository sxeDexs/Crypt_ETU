def rotate_matrix_90_cw(matrix):
    """Поворот матрицы 4x4 на 90 градусов по часовой стрелке"""
    return [[matrix[3 - c][r] for c in range(4)] for r in range(4)]

def cardano_encrypt(P, K1, visualize=False, is_pi_mode=False):
    # Вспомогательная функция для красивого отображения элемента
    def format_val(val):
        if val is None:
            return '.'
        # В учебном режиме вычитаем 72, чтобы получить цифру числа Пи
        return str(val - 72) if is_pi_mode else chr(val)

    # Создаем пустую рабочую матрицу 4x4
    grid = [[None for _ in range(4)] for _ in range(4)]
    p_idx = 0
    angles = [0, 90, 180, 270]
    
    # 4 положения трафарета (0, 90, 180, 270 градусов)
    for step in range(4):
        placed_elements = []
        
        # Запись в отверстия трафарета
        for r in range(4):
            for c in range(4):
                if K1[r][c] == '0' and p_idx < len(P):
                    grid[r][c] = P[p_idx]
                    placed_elements.append(format_val(P[p_idx]))
                    p_idx += 1
        
        # === Блок визуализации текущего шага ===
        if visualize:
            print(f"\n--- Шаг {step + 1} (Поворот трафарета: {angles[step]} градусов) ---")
            print("Трафарет:")
            for row in K1:
                print("  " + " ".join(row))
                
            label = "цифры Пи" if is_pi_mode else "символы"
            print(f"Вставлены {label}: {', '.join(placed_elements) if placed_elements else 'Нет (текст закончился)'}")
            
            print("Рабочая матрица:")
            for row in grid:
                row_display = [format_val(val) for val in row]
                print("  " + " ".join(row_display))
            print("-" * 45)
        # =======================================
                    
        # Поворот трафарета для следующей итерации
        K1 = rotate_matrix_90_cw(K1)
        
    # Считывание зашифрованного текста построчно
    C = []
    for r in range(4):
        for c in range(4):
            if grid[r][c] is not None:
                C.append(grid[r][c])
                
    return C

